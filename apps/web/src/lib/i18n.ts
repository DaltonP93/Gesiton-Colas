export type TKey = keyof (typeof dict)['es'];

export function translator(locale: Locale, terminology?: Terminology) {
  const table = dict[locale] ?? dict.es;
  return (key: TKey, vars: Record<string, string | number> = {}) => {
    const template: string = table[key] ?? dict.es[key] ?? key;
    // La terminología personalizada solo aplica al español (idioma en el que se define).
    const terms: Record<string, string> =
      locale === 'es' && terminology
        ? { ticket: terminology.ticket.toLowerCase(), counter: terminology.counter, service: terminology.service, Ticket: terminology.ticket }
        : { ticket: locale === 'pt' ? 'senha' : locale === 'en' ? 'ticket' : 'turno', counter: '', service: '' };
    const text = template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? terms[k] ?? ''));
    return template.startsWith('{') ? text.charAt(0).toUpperCase() + text.slice(1) : text;
  };
}

